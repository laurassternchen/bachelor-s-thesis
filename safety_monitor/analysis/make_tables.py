#!/usr/bin/env python3
"""Thesis tables (LaTeX booktabs/tabularx + CSV) from the analysis outputs.

Reads only the CSVs written by analyze_runs.py and config/safety_case.yaml,
so every cell is traceable: each table row carries a `% source:` comment
naming the CSV file and column(s) it comes from. Writes to --out-dir
(default bags/analysis/tables/):

  spi_derivation.{tex,csv}       SPI -> goal, hazard, signal, threshold, ...
  speed_limit_results.{tex,csv}  G2 / SPI-1 per config and leg
  keepout_results.{tex,csv}      G3 / SPI-2 and G4 / SPI-3 per config and leg

LaTeX preamble needs: booktabs, tabularx, xurl (for \\path).
Values are mean ± std over the runs of a leg (2 decimals), counts n/10.
In cell text, `name` marks a code name: \\path{name} in LaTeX, plain in CSV.

Usage:
    python3 make_tables.py --analysis-dir bags/analysis
"""
import argparse
import csv
import re
import statistics
from pathlib import Path

import yaml

PKG_DIR = Path(__file__).resolve().parent.parent
CONFIGS = ('base', 'native_keepout', 'native_speed', 'external')
SPI1_TOLERANCE = 0.02  # m/s; safety_case.yaml keeps 0.0, see tolerance_sensitivity.csv
SPEED_LEGS = (('goal1_zone_entry', 'goal1: zone entry'),
              ('goal2_zone_exit', 'goal2: inside the zone and exit'))
GRID_RESOLUTION_M = 0.05
SPI_IDS = ('SPI-1', 'SPI-2', 'SPI-3', 'SPI-4')


# -- input --------------------------------------------------------------------

def read_csv(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def num(value):
    return float(value) if value not in ('', None, 'None') else None


# -- formatting -------------------------------------------------------------

def pm(mean, std, scale=1.0):
    if mean is None:
        return '–'
    return f'{mean * scale:.2f} ± {(std or 0.0) * scale:.2f}'


def pm_values(values):
    values = [v for v in values if v is not None]
    if not values:
        return '–'
    if len(values) == 1:
        return f'{values[0]:.2f}'
    return pm(statistics.fmean(values), statistics.stdev(values))


def status(row):
    return f"{row['supported']}/{row['challenged']}/{row['no_evidence']}"


def latex_cell(text):
    """Plain cell text -> LaTeX: `code` -> \\path{code}, escapes, ± and ≤."""
    parts = re.split(r'(`[^`]*`)', text)
    out = []
    for part in parts:
        if part.startswith('`') and part.endswith('`'):
            out.append(r'\path{' + part[1:-1] + '}')
            continue
        part = (part.replace('\\', r'\textbackslash{}').replace('&', r'\&')
                .replace('%', r'\%').replace('_', r'\_').replace('#', r'\#'))
        part = (part.replace('±', r'$\pm$').replace('≤', r'$\leq$').replace('→', r'$\to$')
                .replace('|', r'$|$').replace('−', r'$-$').replace('>', r'$>$')
                .replace('<', r'$<$'))
        out.append(part)
    return ''.join(out)


def plain_cell(text):
    return text.replace('`', '')


# -- table writer -------------------------------------------------------------

class Table:
    """Rows of plain-text cells, grouped, each with a source comment."""

    def __init__(self, name, caption, label, header, colspec, notes=()):
        self.name, self.caption, self.label = name, caption, label
        self.header, self.colspec, self.notes = header, colspec, list(notes)
        self.items = []  # ('group', title) or ('row', cells, source)

    def group(self, title):
        self.items.append(('group', title))

    def row(self, cells, source):
        self.items.append(('row', cells, source))

    def write(self, out_dir):
        ncol = len(self.header)
        lines = [
            f'% Generated by safety_monitor/analysis/make_tables.py -- do not edit by hand.',
            r'\begin{table}[htbp]',
            r'  \centering',
            r'  \footnotesize',
            f'  \\caption{{{latex_cell(self.caption)}}}',
            f'  \\label{{{self.label}}}',
            f'  \\begin{{tabularx}}{{\\textwidth}}{{{self.colspec}}}',
            r'    \toprule',
            '    ' + ' & '.join(latex_cell(h) for h in self.header) + r' \\',
            r'    \midrule',
        ]
        first_group = True
        for item in self.items:
            if item[0] == 'group':
                if not first_group:
                    lines.append(r'    \addlinespace')
                first_group = False
                lines.append(f'    \\multicolumn{{{ncol}}}{{@{{}}l}}{{\\textit{{{latex_cell(item[1])}}}}} \\\\')
                continue
            _, cells, source = item
            lines.append(f'    % source: {source}')
            lines.append('    ' + ' & '.join(latex_cell(c) for c in cells) + r' \\')
        lines.append(r'    \bottomrule')
        lines.append(r'  \end{tabularx}')
        if self.notes:
            lines.append(r'  \par\smallskip')
            lines.append(r'  \begin{minipage}{\textwidth}\scriptsize')
            lines += ['    ' + latex_cell(n) + r'\par' for n in self.notes]
            lines.append(r'  \end{minipage}')
        lines.append(r'\end{table}')
        (out_dir / f'{self.name}.tex').write_text('\n'.join(lines) + '\n')

        with open(out_dir / f'{self.name}.csv', 'w', newline='') as f:
            writer = csv.writer(f)
            writer.writerow(['group'] + [plain_cell(h) for h in self.header] + ['source'])
            group = ''
            for item in self.items:
                if item[0] == 'group':
                    group = item[1]
                    continue
                _, cells, source = item
                writer.writerow([group] + [plain_cell(c) for c in cells] + [source])
            for n in self.notes:
                writer.writerow(['note', plain_cell(n)] + [''] * (ncol))
        print(f'Wrote {out_dir / self.name}.tex/.csv')


def config_header(first):
    return [first] + [f'`{c}`' for c in CONFIGS]


CONFIG_COLSPEC = r'@{}>{\raggedright\arraybackslash}p{3.3cm}*{4}{>{\centering\arraybackslash}X}@{}'


# -- shared lookups -------------------------------------------------------------

def time_to_goal(runs, config, leg):
    """'mean ± std (successes/n)' over succeeded legs (runs.csv)."""
    rows = [r for r in runs if r['config_id'] == config and r['nav_goal'] == leg]
    ok = [num(r['time_to_goal_s']) for r in rows if r['terminal_status'] == 'succeeded']
    return f'{pm_values(ok)} ({len(ok)}/{len(rows)})'


TIME_TO_GOAL_SOURCE = ('runs.csv: time_to_goal_s (rows with terminal_status = succeeded; '
                       'window_source says monitor window or motion window)')


# -- Table 2: SPI derivation -----------------------------------------------------

SIGNALS = {
    'SPI-1': '`/odom` forward speed (`twist.linear.x`); robot position from TF '
             '`map`→`base_footprint` classified against `zone_map.pgm`; checked at 20 Hz',
    'SPI-2': 'Robot position from TF `map`→`base_footprint`; penetration depth into a keepout '
             'cell of `zone_map.pgm`; checked at 20 Hz',
    'SPI-3': 'Robot position from TF `map`→`base_footprint`; map-based distance to the nearest '
             'keepout cell of `zone_map.pgm`, outside keepout only (not `/scan`); checked at 20 Hz',
    'SPI-4': '|`/cmd_vel_smoothed` − `/cmd_vel`| (linear x); checked on every `/cmd_vel` message',
}
SIGNAL_SOURCE = ('safety_monitor_node.py (_on_odom, _current_position, _tick, _on_cmd_vel) '
                 'and spis.py (SPI1Overspeed..SPI4Intervention.update)')
COMPARISON = {'SPI-1': '>', 'SPI-2': '>', 'SPI-3': '<', 'SPI-4': '>'}
LEADING_LAGGING = {'SPI-1': 'Lagging', 'SPI-2': 'Lagging', 'SPI-3': 'Leading',
                   'SPI-4': 'Informational'}


def exposure_text(ev):
    exp, min_exp = ev['exposure'], ev.get('min_exposure') or {}
    kind = exp['kind']
    if kind == 'speed_zone':
        text = 'Inside a speed zone'
    elif kind == 'near_keepout':
        text = f"Within {exp['within_m']} m of a keepout cell (incl. inside)"
    else:
        text = 'Whole goal window'
    if ev.get('goal_id') is None:
        return text + '; not used for a claim'
    mins = [f'{v} m driven' if k == 'distance_m' else f'{v} s' for k, v in min_exp.items()]
    return text + (f'; min. {", ".join(mins)} for support' if mins else '')


def spi_derivation(case):
    goals, evidence = case['goals'], case['evidence']
    table = Table(
        'spi_derivation',
        'Derivation of the safety performance indicators (SPIs) from the safety argument.',
        'tab:spi-derivation',
        ['', *SPI_IDS],
        r'@{}>{\raggedright\arraybackslash}p{1.9cm}*{4}{>{\raggedright\arraybackslash}X}@{}',
        notes=[
            'All SPIs are evaluated only between goal acceptance and the terminal result. '
            'Events closer than 0.3 s are merged (debounce).',
            f'Tolerance is applied offline. `safety_case.yaml` keeps 0.0 for SPI-1; the results '
            f'tables use {SPI1_TOLERANCE} m/s (sensitivity run, `tolerance_sensitivity.csv`).',
        ])

    def goal_cell(spi):
        gid = evidence[spi].get('goal_id')
        return f"{gid}: {goals[gid]['text']}" if gid else '– (informational)'

    def hazard_cell(spi):
        gid = evidence[spi].get('goal_id')
        return f"{goals[gid]['hazard_id']}: {goals[gid]['hazard']}" if gid else '–'

    def threshold_cell(spi):
        ev = evidence[spi]
        return f"{COMPARISON[spi]} {ev['threshold']} {ev['unit']}"

    def tolerance_cell(spi):
        ev = evidence[spi]
        tol = SPI1_TOLERANCE if spi == 'SPI-1' else float(ev.get('tolerance', 0.0))
        return f"{tol:g} {ev['unit']}" + ('' if ev.get('goal_id') else ' (not used)')

    table.row(['Goal'] + [goal_cell(s) for s in SPI_IDS],
              'safety_case.yaml: evidence.<SPI>.goal_id, goals.<id>.text')
    table.row(['Hazard'] + [hazard_cell(s) for s in SPI_IDS],
              'safety_case.yaml: goals.<id>.hazard_id, goals.<id>.hazard')
    table.row(['Signal'] + [SIGNALS[s] for s in SPI_IDS], SIGNAL_SOURCE)
    table.row(['Threshold'] + [threshold_cell(s) for s in SPI_IDS],
              'safety_case.yaml: evidence.<SPI>.threshold, unit; comparison from spis.py')
    table.row(['Tolerance'] + [tolerance_cell(s) for s in SPI_IDS],
              'safety_case.yaml: evidence.<SPI>.tolerance; SPI-1 overridden to '
              f'{SPI1_TOLERANCE} (tolerance_sensitivity.csv)')
    table.row(['Exposure'] + [exposure_text(evidence[s]) for s in SPI_IDS],
              'safety_case.yaml: evidence.<SPI>.exposure, min_exposure')
    table.row(['Leading / lagging'] + [LEADING_LAGGING[s] for s in SPI_IDS],
              'classification (SPI-1/2 measure the hazard itself, SPI-3 a precursor, '
              'SPI-4 has goal_id null)')
    return table


# -- Table 3: speed limit ---------------------------------------------------------

def speed_limit_results(runs, overspeed, sensitivity):
    table = Table(
        'speed_limit_results',
        f'Speed-limit results (G2 / SPI-1, tolerance {SPI1_TOLERANCE} m/s), mean ± std over '
        'the runs of each leg.',
        'tab:speed-limit-results',
        config_header('Metric'), CONFIG_COLSPEC,
        notes=[
            f'Overspeed = speed above limit + tolerance (0.2 + {SPI1_TOLERANCE} m/s) inside the '
            'speed zone, from `/odom`. Fraction = overspeed duration / time in the speed zone.',
            'G2 status: supported / challenged / no evidence, out of 10 runs. '
            'Time to goal: goal accepted to terminal result, successful legs only '
            '(successes/runs).',
            'goal3 (keepout leg) never enters the speed zone and is omitted.',
        ])

    def over(config, leg):
        return next(r for r in overspeed if r['config_id'] == config and r['nav_goal'] == leg
                    and float(r['tolerance_mps']) == SPI1_TOLERANCE)

    def g2(config, leg):
        return next(r for r in sensitivity if r['config_id'] == config and r['scope'] == leg
                    and r['goal_id'] == 'G2' and float(r['tolerance']) == SPI1_TOLERANCE)

    src = f'spi1_overspeed.csv (tolerance_mps = {SPI1_TOLERANCE}, nav_goal = leg): '
    for leg, title in SPEED_LEGS:
        table.group(title)
        o = {c: over(c, leg) for c in CONFIGS}
        table.row(['Mean speed in zone [m/s]'] + [
            pm(num(o[c]['speed_in_zone_mean_mps_mean']), num(o[c]['speed_in_zone_mean_mps_std']))
            for c in CONFIGS], src + 'speed_in_zone_mean_mps_mean, speed_in_zone_mean_mps_std')
        table.row(['Overspeed duration [s]'] + [
            pm(num(o[c]['overspeed_duration_s_mean']), num(o[c]['overspeed_duration_s_std']))
            for c in CONFIGS], src + 'overspeed_duration_s_mean, overspeed_duration_s_std')
        table.row(['Overspeed distance [m]'] + [
            pm(num(o[c]['overspeed_distance_m_mean']), num(o[c]['overspeed_distance_m_std']))
            for c in CONFIGS], src + 'overspeed_distance_m_mean, overspeed_distance_m_std')
        table.row(['Overspeed fraction [%]'] + [
            pm(num(o[c]['overspeed_fraction_mean']), num(o[c]['overspeed_fraction_std']), 100.0)
            for c in CONFIGS], src + 'overspeed_fraction_mean, overspeed_fraction_std (x 100)')
        table.row(['Runs with overspeed'] + [
            f"{o[c]['n_runs_overspeed']}/{o[c]['n_runs']}" for c in CONFIGS],
            src + 'n_runs_overspeed, n_runs')
        table.row(['Time to goal [s]'] + [time_to_goal(runs, c, leg) for c in CONFIGS],
                  TIME_TO_GOAL_SOURCE)
        table.row(['G2 status (S/C/N)'] + [status(g2(c, leg)) for c in CONFIGS],
                  f'tolerance_sensitivity.csv (tolerance = {SPI1_TOLERANCE}, scope = leg, '
                  'goal_id = G2): supported, challenged, no_evidence')
    return table


# -- Table 4: keepout -------------------------------------------------------------

def keepout_legs(runs):
    """Legs that come within the G4 exposure radius in at least one run."""
    legs = []
    for r in runs:
        if num(r['spi3_exposure_time_s']) and r['nav_goal'] not in legs:
            legs.append(r['nav_goal'])
    return sorted(legs)


def keepout_results(runs, claim_summary, case):
    within = case['evidence']['SPI-3']['exposure']['within_m']
    grid_runs = [r for r in runs if int(r['spi2_count']) > 0
                 and num(r['spi2_peak_value']) <= GRID_RESOLUTION_M + 1e-9]
    grid_note = ', '.join(f"`{r['config_id']}` {r['run_id']} ({r['nav_goal'].split('_')[0]})"
                          for r in grid_runs)
    legs = keepout_legs(runs)
    table = Table(
        'keepout_results',
        'Keepout results (G3 / SPI-2 and G4 / SPI-3), mean ± std over the runs of each leg.',
        'tab:keepout-results',
        config_header('Metric'), CONFIG_COLSPEC,
        notes=[
            'Max penetration and intrusion duration: over runs with an intrusion only. '
            'Min distance: map-based distance to the nearest keepout cell (0 = inside), '
            'all runs. Time below 0.3 m margin: SPI-3 event duration (outside keepout only).',
            f'Penetrations ≤ {GRID_RESOLUTION_M} m (one map cell, the grid resolution): '
            f'{grid_note}. In `native_keepout` run18 the intrusion coincides with an AMCL '
            'correction (≈ 0.12 m pose jump in 0.14 s), not with driving into the zone.',
            f'Only legs that come within the G4 exposure radius ({within} m) of keepout are '
            'listed; goal1 never does. G3/G4 status: supported / challenged / no evidence, out '
            'of 10 runs. Time to goal: successful legs only (successes/runs).',
        ])

    def leg_runs(config, leg):
        return [r for r in runs if r['config_id'] == config and r['nav_goal'] == leg]

    def claim(config, leg, goal):
        return next(r for r in claim_summary if r['config_id'] == config
                    and r['nav_goal'] == leg and r['goal_id'] == goal)

    titles = {'goal2_zone_exit': 'goal2: zone exit, past the keepout corner',
              'goal3_keepout': 'goal3: around the keepout zone'}
    for leg in legs:
        table.group(titles.get(leg, leg))
        rr = {c: leg_runs(c, leg) for c in CONFIGS}
        hit = {c: [r for r in rr[c] if int(r['spi2_count']) > 0] for c in CONFIGS}
        table.row(['Runs with intrusion'] + [f'{len(hit[c])}/{len(rr[c])}' for c in CONFIGS],
                  'runs.csv: spi2_count > 0')
        table.row(['Max penetration [m]'] + [
            pm_values([num(r['spi2_peak_value']) for r in hit[c]]) for c in CONFIGS],
            'runs.csv: spi2_peak_value (runs with spi2_count > 0)')
        table.row(['Intrusion duration [s]'] + [
            pm_values([num(r['spi2_total_duration_s']) for r in hit[c]]) for c in CONFIGS],
            'runs.csv: spi2_total_duration_s (runs with spi2_count > 0)')
        table.row(['Min distance to keepout [m]'] + [
            pm_values([num(r['min_keepout_distance_m']) for r in rr[c]]) for c in CONFIGS],
            'runs.csv: min_keepout_distance_m')
        table.row(['Time below 0.3 m margin [s]'] + [
            pm_values([num(r['spi3_total_duration_s']) for r in rr[c]]) for c in CONFIGS],
            'runs.csv: spi3_total_duration_s')
        table.row(['Time to goal [s]'] + [time_to_goal(runs, c, leg) for c in CONFIGS],
                  TIME_TO_GOAL_SOURCE)
        table.row(['G3 status (S/C/N)'] + [status(claim(c, leg, 'G3')) for c in CONFIGS],
                  'claim_summary.csv (nav_goal = leg, goal_id = G3): supported, challenged, '
                  'no_evidence')
        table.row(['G4 status (S/C/N)'] + [status(claim(c, leg, 'G4')) for c in CONFIGS],
                  'claim_summary.csv (nav_goal = leg, goal_id = G4): supported, challenged, '
                  'no_evidence')
    return table, legs


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--analysis-dir', default='bags/analysis', type=Path)
    parser.add_argument('--out-dir', type=Path, help='default: <analysis-dir>/tables')
    parser.add_argument('--safety-case', default=PKG_DIR / 'config' / 'safety_case.yaml',
                        type=Path)
    args = parser.parse_args()
    out_dir = args.out_dir or args.analysis_dir / 'tables'
    out_dir.mkdir(parents=True, exist_ok=True)

    with open(args.safety_case) as f:
        case = yaml.safe_load(f)['safety_case']
    runs = read_csv(args.analysis_dir / 'runs.csv')
    spi_derivation(case).write(out_dir)
    speed_limit_results(runs, read_csv(args.analysis_dir / 'spi1_overspeed.csv'),
                        read_csv(args.analysis_dir / 'tolerance_sensitivity.csv')).write(out_dir)
    table, legs = keepout_results(runs, read_csv(args.analysis_dir / 'claim_summary.csv'), case)
    table.write(out_dir)
    print(f'Keepout table legs (within G4 exposure radius): {", ".join(legs)}')


if __name__ == '__main__':
    main()
